#!/usr/bin/env node
// Writes docs/API-REFERENCE.md from Operation[] of the built package (family × model × fields): run `npm run build`
// first. `--check` exits 1 when the committed file is not what the snapshot renders. The file is never edited by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { readSnapshot, ROOT } from "./spec-lib.mjs";

const OUT = `${ROOT}docs/API-REFERENCE.md`;

async function load() {
  const dist = (path) => import(pathToFileURL(`${ROOT}dist/${path}`).href);
  const [ops, classify, overlay, support, fields, server] = await Promise.all([
    dist("spec/operations.js"),
    dist("spec/classify.js"),
    dist("spec/overlay.js"),
    dist("spec/support.js"),
    dist("spec/fields.js"),
    dist("server.js"),
  ]);
  return { ...ops, ...classify, ...overlay, ...support, ...fields, toolDefinitions: server.toolDefinitions };
}

const mb = (bytes) => `${Math.round(bytes / 1_000_000)} MB`;

function classTable(m) {
  const rows = m.OPERATION_CLASSES.map((cls) => {
    const count = m.OPERATIONS.filter((op) => op.class === cls).length;
    return `| ${cls} | ${count} | ${m.EXPOSABLE_CLASSES.has(cls) ? "yes" : "never"} |`;
  });
  return ["| class | operations | exposable |", "|---|---|---|", ...rows];
}

function toolTable(m) {
  const rows = m.toolDefinitions().map((t) => `| \`${t.name}\` | ${t.description.replaceAll("|", "\\|")} |`);
  return ["| tool | what it does |", "|---|---|", ...rows];
}

function operationRow(m, op) {
  const quotable = m.quoteAllowed(op) ? "yes" : "no";
  return `| ${op.model ?? "—"} | \`${op.id}\` | \`${op.method} ${op.path}\` | ${op.class} | ${m.supportOf(op)} | ${quotable} | ${op.async} | ${op.facts.bodies.join(" + ") || "none"} |`;
}

function operationDetail(m, op) {
  const head = [`#### ${op.model ?? op.id} — \`${op.method} ${op.path}\``, "", op.summary, ""];
  const fieldRows = m.fieldSummaries(op).map((f) => `| \`${f.name}\` | ${f.kind.replaceAll("|", "\\|")} | ${f.required ? "yes" : ""} |`);
  const table = fieldRows.length === 0 ? ["No body."] : ["| field | kind | required |", "|---|---|---|", ...fieldRows];
  const limits = m.fileLimitsOf(op).map((l) => `\`${l.field}\` ${mb(l.maxBytes)}${l.stated ? "" : " (not stated; this server's cap)"}${l.maxItems === null ? "" : ` × ${l.maxItems}`}`);
  const rules = m.rulesOf(op).map((text) => `- ${text}`);
  const params = m.parameterSummaries(op).map((p) => `\`${p}\``);
  if (params.length) head.push(`Parameters: ${params.join(", ")}.`, "");
  return [...head, ...table, "", ...(limits.length ? [`File limits: ${limits.join("; ")}.`, ""] : []), ...(rules.length ? ["Rules:", ...rules, ""] : [])];
}

function familySection(m, family) {
  const ops = m.OPERATIONS.filter((op) => op.family === family);
  const served = ops.filter((op) => ["curated", "raw"].includes(m.supportOf(op)));
  return [
    `### ${family}`,
    "",
    "| model | operation | path | class | support | quotable | async | body |",
    "|---|---|---|---|---|---|---|---|",
    ...ops.map((op) => operationRow(m, op)),
    "",
    ...served.flatMap((op) => operationDetail(m, op)),
  ];
}

export async function render() {
  const m = await load();
  const snapshot = readSnapshot();
  const families = m.FAMILIES.filter((family) => m.OPERATIONS.some((op) => op.family === family && m.isExposable(op)));
  return [
    "# Ideogram API — reference",
    "",
    `Generated by \`scripts/api-reference.mjs\` from the specification snapshot of ${snapshot.date} (\`spec/openapi.json\`,`,
    `raw sha256 \`${snapshot.raw_sha256}\`). Do not edit by hand: \`npm run build && node scripts/api-reference.mjs\`.`,
    "",
    `Base URL \`https://api.ideogram.ai\`, authentication by the \`Api-Key\` header. The provider's documentation index: ${m.DOCS_INDEX_URL}.`,
    "Fields of the operations this release serves (curated or raw) are listed below their family's table.",
    "",
    "## Classes",
    "",
    ...classTable(m),
    "",
    "## Tools of this release",
    "",
    ...toolTable(m),
    "",
    "## Families",
    "",
    ...families.flatMap((family) => familySection(m, family)),
  ]
    .join("\n")
    .replace(/\n+$/, "\n");
}

async function main() {
  const text = await render();
  if (!process.argv.includes("--check")) {
    writeFileSync(OUT, text);
    console.log(`docs/API-REFERENCE.md: ${Buffer.byteLength(text)} bytes`);
    return 0;
  }
  if (readFileSync(OUT, "utf8") === text) return 0;
  console.error("docs/API-REFERENCE.md is not what the snapshot renders: run node scripts/api-reference.mjs");
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().then(
    (code) => process.exit(code),
    (error) => {
      console.error(`api-reference: ${error instanceof Error ? error.message : error}`);
      process.exit(2);
    },
  );
}
